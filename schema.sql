-- ECSA Strategy Arena v1 database schema
-- Run in Supabase Dashboard > SQL Editor.
-- This starter schema supports public score submission and public leaderboard reads.
-- For a high-stakes/official competition, add authenticated student identity and
-- server-side score validation before opening registration publicly.

create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  student_name text not null check (char_length(student_name) between 2 and 80),
  register_number text not null check (char_length(register_number) between 3 and 30),
  semester text not null check (semester in ('S1','S2','S3','S4','S5','S6','S7','S8')),
  game_id text not null check (game_id in ('logic','signal','network','escape','tower','memory','decision')),
  score integer not null check (score between 0 and 1000),
  correct integer not null check (correct between 0 and 20),
  total integer not null check (total between 1 and 20),
  elapsed_seconds integer not null check (elapsed_seconds between 0 and 7200),
  created_at timestamptz not null default now()
);

create index if not exists scores_score_idx on public.scores(score desc);
create index if not exists scores_game_idx on public.scores(game_id);
create index if not exists scores_register_idx on public.scores(register_number);

alter table public.scores enable row level security;

-- Public can read scores for the leaderboard.
create policy "Scores are publicly readable"
on public.scores for select
to anon, authenticated
using (true);

-- Public can submit a score. Do not treat client-calculated scores as tamper-proof.
create policy "Players can submit scores"
on public.scores for insert
to anon, authenticated
with check (
  char_length(student_name) between 2 and 80
  and char_length(register_number) between 3 and 30
  and semester in ('S1','S2','S3','S4','S5','S6','S7','S8')
  and game_id in ('logic','signal','network','escape','tower','memory','decision')
  and score between 0 and 1000
  and correct between 0 and total
  and total between 1 and 20
  and elapsed_seconds between 0 and 7200
);

-- No public UPDATE or DELETE policies are created.
